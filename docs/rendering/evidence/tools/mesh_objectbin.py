d = open(P,'rb').read()
print("file size:", len(d), " expected 2048*16*16+4 =", 2048*256+4)
mask_enc = d[:2048*256]; chk = struct.unpack_from('<i', d, 2048*256)[0]
# checksum as the client computes it (over the still-encrypted bytes).
# The client stores into `char` (signed on MSVC x86) and uses C's truncating `%`,
# accumulated in a 32-bit int.
n = 0
for m in range(2048):
    for y in range(16):
        row = d[m*256 + y*16: m*256 + y*16 + 16]
        for v in row:
            sv = v if v < 128 else v - 256
            r = sv - int(sv / 4) * 4        # C truncating %
            n += r + 2*y + 5*m
n32 = n & 0xFFFFFFFF
print("checksum (signed char, C %%, int32 wrap): %d  (signed %d)" % (n32, n32 - (1 << 32) if n32 >= (1 << 31) else n32))
print("checksum stored at 0x%X        : %d  (signed %d)" % (2048*256, chk & 0xFFFFFFFF, chk))
print("MATCH:", n32 == (chk & 0xFFFFFFFF))

key = KEYS.split(b'\x00')[0]; kl = len(key)
dec = bytearray(2048*256)
for j in range(len(dec)):
    dec[j] = (mask_enc[j] - key[j % kl] - j) & 0xFF
vals = collections.Counter(dec)
print("\ndecrypted value histogram:", dict(sorted(vals.items())))
zero_masks = sum(1 for m in range(2048) if not any(dec[m*256:(m+1)*256]))
